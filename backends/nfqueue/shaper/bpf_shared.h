/* Data layout shared by the tc eBPF program (lagsw.bpf.c) and the user-space loader. Plain C so both can include it. */
#ifndef NFQUEUE_SHAPER_BPF_SHARED_H_
#define NFQUEUE_SHAPER_BPF_SHARED_H_

#include <linux/types.h>

#define LAGSW_MAX_STAGES   16
#define LAGSW_MAX_RULES	   16
#define LAGSW_MAX_MATCHES  8
#define LAGSW_MAX_ADDRS	   65536
#define LAGSW_MAX_IFACES   32
#define LAGSW_NORMAL_STEPS 1024
/* Longest total delay the program stamps; the fq horizon is set just above it. */
#define LAGSW_TOTAL_DELAY_CAP_NS (890ull * 1000000000ull)
/* The normal quantile table stores the standard score multiplied by this factor. */
#define LAGSW_NORMAL_SCALE 1000000

/* Match kinds; they mirror linux_shared::MatchKind without the implicit "IPv4" match. */
enum lagsw_match_kind
{
	LAGSW_MATCH_PROTOCOL = 1,
	LAGSW_MATCH_TCP_FLAG,
	LAGSW_MATCH_ADDRESS,
	LAGSW_MATCH_PORT,
	LAGSW_MATCH_IIF,
	LAGSW_MATCH_OIF,
};

/* Rule::hooks bits: which kind of packet a rule applies to, as seen at egress. */
#define LAGSW_HOOK_LOCAL   1u /* generated by this host */
#define LAGSW_HOOK_FORWARD 2u /* routed through this host */

struct lagsw_match
{
	__u8  kind;
	__u8  negated;
	__u8  proto;	/* PROTOCOL, PORT: IPPROTO_TCP or IPPROTO_UDP */
	__u8  endpoint; /* ADDRESS, PORT: 0 = source, 1 = destination */
	__u16 port;		/* PORT, host byte order */
	__u8  flag;		/* TCP_FLAG: the flag bit */
	__u8  is_set;	/* ADDRESS: `value` is a set id instead of an address */
	__u32 value;	/* ADDRESS: address in network byte order or set id; IIF/OIF: interface index */
};

struct lagsw_rule
{
	__u8			   count;
	__u8			   hooks;
	__u16			   pad;
	struct lagsw_match matches[LAGSW_MAX_MATCHES];
};

enum lagsw_mode
{
	LAGSW_MODE_DELAY = 1, /* hold every packet for the delay (with jitter for the baseline model) */
	LAGSW_MODE_DROP,	  /* drop every packet */
	LAGSW_MODE_BATCH,	  /* the first packet opens a batch; every packet of the batch leaves at the batch deadline */
};

enum lagsw_model
{
	LAGSW_MODEL_FIXED = 0,
	LAGSW_MODEL_UNIFORM,
	LAGSW_MODEL_NORMAL,
};

/* One shaping stage: a profile or the always-on baseline. Stages are evaluated in index order and their delays add up. */
struct lagsw_stage
{
	__u32			  active;
	__u32			  mode;
	__u32			  model;
	__u32			  preserve_order;
	__u32			  rule_count;
	__u32			  pad;
	__u64			  delay_ns;
	__u64			  jitter_ns;
	__u64			  max_delay_ns;
	struct lagsw_rule rules[LAGSW_MAX_RULES];
};

/* Mutable per-stage state, written by the program. */
struct lagsw_state
{
	__u64 last_release;
	__u64 batch_deadline;
};

/* Per-CPU counters of one stage. */
struct lagsw_stats
{
	__u64 matched;
	__u64 delayed;
	__u64 dropped;
	__u64 clamped;
};

struct lagsw_addr_key
{
	__u32 set;
	__u32 addr;
};

struct lagsw_ifinfo
{
	__u32 l2_len; /* 14 for Ethernet, 0 for devices without a link-layer header */
};

#endif
